"""Integration tests: real Docker -> Yosys -> RTL synthesis.

These tests need a working Docker daemon AND the EDA image (build with
``docker build -t aemp-eda-base:0.1.0 docker/``). When either is missing
they SKIP - they never mock, and unit tests (tests/unit) never touch
Docker at all (AGENTS.md §12).
"""

import subprocess
from pathlib import Path

import pytest

IMAGE = "aemp-eda-base:0.1.0"
REPO_ROOT = Path(__file__).resolve().parents[2]
RTL_DIR = REPO_ROOT / "examples" / "rtl"

pytestmark = pytest.mark.integration


def _run(args: list[str], timeout: float = 300.0) -> subprocess.CompletedProcess:
    return subprocess.run(args, capture_output=True, text=True, timeout=timeout)


@pytest.fixture(scope="module")
def eda_environment() -> None:
    """Skip the whole module unless Docker and the EDA image are ready."""
    try:
        daemon = _run(
            ["docker", "version", "--format", "{{.Server.Version}}"], timeout=30
        )
    except (OSError, subprocess.SubprocessError):
        pytest.skip("Docker not installed or not runnable on this host")
    if daemon.returncode != 0:
        pytest.skip(f"Docker daemon not available: {daemon.stderr.strip()[:120]}")
    image = _run(["docker", "image", "inspect", IMAGE], timeout=30)
    if image.returncode != 0:
        pytest.skip(f"EDA image missing - build it: docker build -t {IMAGE} docker/")


def _synth_to(out_dir: Path, include_stat: bool) -> subprocess.CompletedProcess:
    script = (
        "read_verilog /rtl/simple_counter.v; "
        "hierarchy -check -top simple_counter; "
        "synth -top simple_counter; "
        + ("stat; " if include_stat else "")
        + "write_verilog -noattr /out/synthesized.v"
    )
    return _run(
        [
            "docker", "run", "--rm",
            "-v", f"{RTL_DIR.as_posix()}:/rtl:ro",
            "-v", f"{out_dir.as_posix()}:/out",
            IMAGE,
            "yosys", "-p", script,
        ]
    )


def test_yosys_version_in_container(eda_environment: None) -> None:
    result = _run(["docker", "run", "--rm", IMAGE, "yosys", "-V"])
    assert result.returncode == 0
    assert "Yosys" in result.stdout
    assert "git sha1" in result.stdout  # real build identity, never a guess


def test_rtl_synthesis_produces_real_netlist(
    tmp_path: Path, eda_environment: None
) -> None:
    out_dir = tmp_path / "out"
    out_dir.mkdir()
    result = _synth_to(out_dir, include_stat=True)
    assert result.returncode == 0, result.stderr

    netlist = out_dir / "synthesized.v"
    assert netlist.is_file()
    text = netlist.read_text(encoding="utf-8")
    assert "module simple_counter" in text
    assert "Generated by Yosys" in text  # tool-stamped output, not hand-written
    assert "Number of cells" in result.stdout  # stat comes from the real tool


def test_synthesis_is_reproducible(tmp_path: Path, eda_environment: None) -> None:
    """Two independent container runs must produce byte-identical netlists."""
    first = _synth_to(tmp_path / "run1", include_stat=False)
    second = _synth_to(tmp_path / "run2", include_stat=False)
    assert first.returncode == 0, first.stderr
    assert second.returncode == 0, second.stderr

    netlist_1 = (tmp_path / "run1" / "synthesized.v").read_text(encoding="utf-8")
    netlist_2 = (tmp_path / "run2" / "synthesized.v").read_text(encoding="utf-8")
    assert netlist_1 == netlist_2
