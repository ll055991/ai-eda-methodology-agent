"""Run orchestration: connects the M1 run lifecycle with M2 tool drivers.

Deliberately thin and the ONLY place where runs and drivers meet
(AGENTS.md §14): RunManager owns run state, drivers own tool semantics,
and this service sequences them and translates
:class:`aemp.drivers.models.ToolExecutionResult` facts into the run
envelope via Run's primitive record methods. Neither package imports the
other; the M3 flow engine will generalize this single-step wiring into
multi-step flows. Drivers stay decoupled from each other: RunService
holds one driver per tool and connects tools at the FLOW level
(yosys-mapped netlist feeds the OpenSTA run - never driver-to-driver).

State semantics (nothing smuggled):

- run lifecycle success/failed mirrors the EXECUTION outcome only;
- ``engineering_status`` stays ``unknown`` - engineering judgment is the
  QA engine's job (M5);
- an environment failure fails the RUN while ``execution.status`` stays
  ``unknown`` (the tool never ran; unknown != failed).
"""

from __future__ import annotations

import shutil
from collections.abc import Sequence
from pathlib import Path
from typing import Protocol

from aemp.core.errors import InvalidRequestError
from aemp.core.logging import get_logger
from aemp.drivers.errors import ToolEnvironmentError
from aemp.drivers.models import ToolExecutionResult
from aemp.runs.manager import Run, RunManager

logger = get_logger(__name__)

_SYNTH_STEP_ID = "synth"
_STA_STEP_ID = "sta"
_SYNTH_SCRIPT_TEMPLATE = """\
# Generated by aemp RunService for run {run_id} (frozen run input).
read_verilog inputs/{rtl_name}
hierarchy -check -top {top}
synth -top {top}
stat
write_verilog -noattr artifacts/synthesized.v
"""

_STA_SCRIPT_TEMPLATE = """\
# Generated by aemp RunService for run {run_id} (frozen run input).
read_liberty inputs/{liberty_name}
read_verilog inputs/{netlist_name}
link_design {top}
read_sdc inputs/{sdc_name}
report_checks
report_worst_slack
report_tns
"""


class ToolDriverProtocol(Protocol):
    """Minimal driver surface the service needs (structural typing).

    ``YosysDriver`` and ``OpenSTADriver`` satisfy it; unit tests satisfy
    it with fakes, so no Docker is required to test the orchestration.
    (Named ``SynthDriver`` in M2.4 when only synthesis existed.)
    """

    def get_version(self, timeout_s: float = 120.0) -> str: ...

    def run_script(
        self, *, workspace: Path, script: Path, timeout_s: float = 300.0
    ) -> ToolExecutionResult: ...


class RunService:
    """Coordinates RunManager with the tool drivers (one method per step)."""

    def __init__(
        self,
        *,
        manager: RunManager,
        yosys: ToolDriverProtocol | None = None,
        opensta: ToolDriverProtocol | None = None,
    ) -> None:
        self._manager = manager
        self._yosys = yosys
        self._opensta = opensta

    def run_synth(
        self,
        *,
        rtl: Path,
        top: str,
        timeout_s: float = 600.0,
        run_id: str | None = None,
    ) -> Run:
        """Run one Yosys synthesis step as a formal, traceable Run.

        Lifecycle: create run -> freeze inputs into the run workspace ->
        record step/tool identity -> mark running -> execute through the
        driver -> record execution facts and artifacts -> finalize.

        Args:
            rtl: Host path of the RTL file to synthesize.
            top: Top module name inside the RTL.
            timeout_s: Hard wall-clock bound for the container execution.
            run_id: Optional explicit run id.

        Returns:
            The finalized :class:`Run` (read ``run.status`` / ``run.json``).

        Raises:
            InvalidRequestError: On missing RTL / empty top / a missing
                yosys driver configuration (nothing is created).
            ToolEnvironmentError: Docker daemon/image unusable; the run is
                finalized as failed (execution stays ``unknown``) and the
                error is re-raised.
        """
        rtl_path = Path(rtl)
        if not rtl_path.is_file():
            msg = f"RTL file does not exist: {rtl_path}"
            raise InvalidRequestError(msg)
        if not top or not top.strip():
            msg = "top must be a non-empty module name"
            raise InvalidRequestError(msg)
        if self._yosys is None:
            msg = "RunService has no yosys driver configured"
            raise InvalidRequestError(msg)

        run = self._manager.create_run(
            "yosys.synthesis", tool_name="yosys", run_id=run_id
        )
        self._freeze_inputs(run, rtl_path, top)
        run.record_step(_SYNTH_STEP_ID)
        run.mark_running()
        try:
            version = self._yosys.get_version()
            result = self._yosys.run_script(
                workspace=run.run_dir,
                script=run.run_dir / "synth.ys",
                timeout_s=timeout_s,
            )
        except ToolEnvironmentError as exc:
            self._fail_on_environment(run, exc)
            raise

        run.record_tool(
            name="yosys",
            version=version,
            path=None,  # container-side binary path is not probed in M2.x
            argv=("yosys", "-s", "synth.ys"),
        )
        netlist = run.run_dir / "artifacts" / "synthesized.v"
        self._record_result(
            run, result, log_prefix="yosys", artifacts=((netlist, "netlist"),)
        )
        run.finalize(
            "success" if result.succeeded else "failed",
            engineering_status="unknown",
            engineering_summary=(
                "execution facts only; engineering judgment arrives with the QA engine (M5)"
            ),
        )
        return run

    def run_sta(
        self,
        *,
        netlist: Path,
        liberty: Path,
        sdc: Path,
        top: str,
        timeout_s: float = 600.0,
        run_id: str | None = None,
    ) -> Run:
        """Run one OpenSTA timing analysis step as a formal, traceable Run.

        STA inputs (frozen into the run workspace):
            netlist  - a Liberty-MAPPED netlist (generic yosys output has
                       no standard cells and cannot be linked)
            liberty  - demo standard-cell library with timing models
            sdc      - clock and input/output constraints

        OpenSTA writes reports to stdout, so the whole tool stdout is
        archived as ``artifacts/timing.rpt`` in addition to the log files.

        Raises:
            InvalidRequestError: Missing input files / empty top / a
                missing opensta driver configuration.
            ToolEnvironmentError: Docker daemon/image unusable; the run is
                finalized as failed (execution stays ``unknown``) and the
                error is re-raised.
        """
        netlist_path, liberty_path, sdc_path = Path(netlist), Path(liberty), Path(sdc)
        for label, path in (
            ("Netlist", netlist_path),
            ("Liberty", liberty_path),
            ("SDC", sdc_path),
        ):
            if not path.is_file():
                msg = f"{label} file does not exist: {path}"
                raise InvalidRequestError(msg)
        if not top or not top.strip():
            msg = "top must be a non-empty module name"
            raise InvalidRequestError(msg)
        if self._opensta is None:
            msg = "RunService has no opensta driver configured"
            raise InvalidRequestError(msg)

        run = self._manager.create_run(
            "opensta.timing", tool_name="opensta", run_id=run_id
        )
        self._freeze_sta_inputs(run, netlist_path, liberty_path, sdc_path, top)
        run.record_step(_STA_STEP_ID)
        run.mark_running()
        try:
            version = self._opensta.get_version()
            result = self._opensta.run_script(
                workspace=run.run_dir,
                script=run.run_dir / "sta.tcl",
                timeout_s=timeout_s,
            )
        except ToolEnvironmentError as exc:
            self._fail_on_environment(run, exc)
            raise

        run.record_tool(
            name="opensta",
            version=version,
            path=None,
            argv=("sta", "-no_splash", "-exit", "sta.tcl"),
        )
        # archive the tool stdout as the timing report ONLY on success: a
        # failed run's stdout is not a valid report (logs still capture it)
        timing_report = run.run_dir / "artifacts" / "timing.rpt"
        artifacts: list[tuple[Path, str]] = []
        if result.succeeded:
            timing_report.write_text(result.stdout, encoding="utf-8", newline="")
            artifacts.append((timing_report, "timing_report"))
        self._record_result(
            run,
            result,
            log_prefix="opensta",
            artifacts=tuple(artifacts),
        )
        run.finalize(
            "success" if result.succeeded else "failed",
            engineering_status="unknown",
            engineering_summary=(
                "execution facts only; timing verdicts arrive with the "
                "timing parser and the QA engine (M4/M5)"
            ),
        )
        return run

    # -- internals --------------------------------------------------------

    def _fail_on_environment(self, run: Run, exc: ToolEnvironmentError) -> None:
        """Record an environment failure: run failed, execution unknown."""
        logger.warning("run %s failed in pre-flight/execution: %s", run.run_id, exc)
        run.add_diagnostic(severity="error", code="environment", message=str(exc))
        run.finalize(
            "failed",
            execution_status="unknown",  # the tool never ran
            engineering_summary=f"EDA environment failure: {exc}"[:4000],
        )

    def _freeze_inputs(self, run: Run, rtl_path: Path, top: str) -> None:
        """Copy the RTL into the run workspace and register the frozen inputs.

        The container can only see the run directory (the workspace), so
        inputs are frozen into it; hashes of the frozen copies become the
        traceable input evidence.
        """
        inputs_dir = run.run_dir / "inputs"
        inputs_dir.mkdir(exist_ok=True)
        frozen_rtl = inputs_dir / rtl_path.name
        shutil.copyfile(rtl_path, frozen_rtl)
        run.add_frozen_input(frozen_rtl, role="rtl")

        script_path = run.run_dir / "synth.ys"
        script_path.write_text(
            _SYNTH_SCRIPT_TEMPLATE.format(
                run_id=run.run_id, rtl_name=rtl_path.name, top=top
            ),
            encoding="utf-8",
        )
        run.add_frozen_input(script_path, role="synth_script")

    def _freeze_sta_inputs(
        self,
        run: Run,
        netlist_path: Path,
        liberty_path: Path,
        sdc_path: Path,
        top: str,
    ) -> None:
        """Freeze netlist/liberty/sdc into the workspace and write sta.tcl."""
        inputs_dir = run.run_dir / "inputs"
        inputs_dir.mkdir(exist_ok=True)
        frozen: list[tuple[Path, str]] = []
        for source, role in (
            (netlist_path, "netlist"),
            (liberty_path, "liberty"),
            (sdc_path, "sdc"),
        ):
            target = inputs_dir / source.name
            shutil.copyfile(source, target)
            frozen.append((target, role))
        for target, role in frozen:
            run.add_frozen_input(target, role=role)

        script_path = run.run_dir / "sta.tcl"
        script_path.write_text(
            _STA_SCRIPT_TEMPLATE.format(
                run_id=run.run_id,
                liberty_name=liberty_path.name,
                netlist_name=netlist_path.name,
                top=top,
                sdc_name=sdc_path.name,
            ),
            encoding="utf-8",
        )
        run.add_frozen_input(script_path, role="sta_script")

    def _record_result(
        self,
        run: Run,
        result: ToolExecutionResult,
        *,
        log_prefix: str,
        artifacts: Sequence[tuple[Path, str]],
    ) -> None:
        """Persist execution output and map the result into the envelope.

        Args:
            artifacts: (path, role) pairs registered only when the file
                exists - claimed outputs must exist (M1 semantics), so a
                failed execution that produced nothing claims nothing.
        """
        stdout_log = run.run_dir / "logs" / f"{log_prefix}.stdout.log"
        stderr_log = run.run_dir / "logs" / f"{log_prefix}.stderr.log"
        stdout_log.write_text(result.stdout, encoding="utf-8", newline="")
        stderr_log.write_text(result.stderr, encoding="utf-8", newline="")

        run.record_execution(
            status=result.status,
            exit_code=result.exit_code,
            duration_ms=result.duration_ms,
            command=result.command,
            cwd=str(result.cwd),
            log_path=f"logs/{log_prefix}.stdout.log",
            log_bytes=stdout_log.stat().st_size,
            log_truncated=result.stdout_truncated,
        )
        if result.timed_out:
            run.add_diagnostic(
                severity="error",
                code="timeout",
                message="tool execution timed out; the container was removed",
            )
        run.add_artifact(stdout_log, role="log_stdout")
        run.add_artifact(stderr_log, role="log_stderr")
        for path, role in artifacts:
            if path.is_file():
                run.add_artifact(path, role=role)
