"""Step operations: per-tool script generation and output collection.

An operation pairs a tool driver with the knowledge of HOW to run one
kind of step (script template, tool argv, what counts as a produced
artifact) and, where a parser exists, how to turn the produced report
into structured metrics. The flow engine stays generic; the two v1
operations are ``yosys.synthesize`` (Liberty-mapped synthesis) and
``opensta.timing_analysis``.
"""

from __future__ import annotations

from pathlib import Path
from typing import Protocol

from aemp.drivers.models import ToolExecutionResult
from aemp.parsers.opensta import OpenSTAParser
from aemp.runs.manager import Run

__all__ = ["OpenSTATimingOperation", "StepOperation", "YosysSynthesizeOperation"]


class StepOperation(Protocol):
    """Structural interface the flow engine relies on (no base class)."""

    tool_name: str

    def prepare(
        self, run: Run, step, resolved: dict[str, str]
    ) -> tuple[Path, tuple[str, ...]]: ...

    def collect_outputs(
        self, run: Run, step, result: ToolExecutionResult
    ) -> list[tuple[Path, str]]: ...

    def parse_metrics(self, run_dir: Path, step) -> dict[str, float] | None: ...


_MAPPED_SYNTH_TEMPLATE = """\
# Generated by aemp FlowEngine for run {run_id} (frozen flow step: {step_id}).
# Liberty-mapped synthesis - generic netlists cannot be linked by OpenSTA.
read_verilog {rtl}
hierarchy -check -top {top}
proc
opt
fsm
opt
memory
opt
techmap
opt
dfflibmap -liberty {liberty}
abc -liberty {liberty}
setundef -zero
splitnets
opt_clean -purge
stat -liberty {liberty}
write_verilog -noattr {netlist}
"""

_STA_TEMPLATE = """\
# Generated by aemp FlowEngine for run {run_id} (frozen flow step: {step_id}).
# Reports go to stdout; the engine archives stdout as the timing report.
read_liberty {liberty}
read_verilog {netlist}
link_design {top}
read_sdc {sdc}
report_checks
report_worst_slack
report_tns
"""


class YosysSynthesizeOperation:
    """``yosys.synthesize``: Liberty-mapped synthesis of one RTL file."""

    tool_name = "yosys"

    def prepare(
        self, run: Run, step, resolved: dict[str, str]
    ) -> tuple[Path, tuple[str, ...]]:
        netlist_path = f"artifacts/{step.outputs['netlist']}"
        script_path = run.run_dir / "synth.ys"
        script_path.write_text(
            _MAPPED_SYNTH_TEMPLATE.format(
                run_id=run.run_id,
                step_id=step.id,
                rtl=resolved["rtl"],
                liberty=resolved["liberty"],
                top=resolved["top"],
                netlist=netlist_path,
            ),
            encoding="utf-8",
        )
        return script_path, ("yosys", "-s", "synth.ys")

    def collect_outputs(
        self, run: Run, step, result: ToolExecutionResult
    ) -> list[tuple[Path, str]]:
        produced = run.run_dir / "artifacts" / step.outputs["netlist"]
        return [(produced, f"{step.id}.netlist")]

    def parse_metrics(self, run_dir: Path, step) -> dict[str, float] | None:
        return None  # synthesis stats have no parser yet (M4 = OpenSTA only)


class OpenSTATimingOperation:
    """``opensta.timing_analysis``: STA over a Liberty-mapped netlist.

    OpenSTA 3.1.0 writes reports to stdout (no ``redirect`` command), so
    on success the engine-archived stdout IS the timing report artifact.
    """

    tool_name = "opensta"

    def prepare(
        self, run: Run, step, resolved: dict[str, str]
    ) -> tuple[Path, tuple[str, ...]]:
        script_path = run.run_dir / "sta.tcl"
        script_path.write_text(
            _STA_TEMPLATE.format(
                run_id=run.run_id,
                step_id=step.id,
                liberty=resolved["liberty"],
                netlist=resolved["netlist"],
                top=resolved["top"],
                sdc=resolved["sdc"],
            ),
            encoding="utf-8",
        )
        return script_path, ("sta", "-no_splash", "-exit", "sta.tcl")

    def collect_outputs(
        self, run: Run, step, result: ToolExecutionResult
    ) -> list[tuple[Path, str]]:
        report = run.run_dir / "artifacts" / step.outputs["report"]
        artifacts: list[tuple[Path, str]] = []
        if result.succeeded:  # a failed stdout is not a valid report
            report.write_text(result.stdout, encoding="utf-8", newline="")
            artifacts.append((report, f"{step.id}.report"))
        return artifacts

    def parse_metrics(self, run_dir: Path, step) -> dict[str, float] | None:
        """Parse the step's declared report into flat structured metrics.

        Uses the M4 OpenSTAParser (pure, no Docker); returns None when the
        step declares no parsable report. A missing metric is absent from
        the dict - never 0 (unknown != 0).
        """
        report_name = step.outputs.get("report")
        if not report_name:
            return None
        report_path = run_dir / "artifacts" / report_name
        if not report_path.is_file():
            return None
        return OpenSTAParser().parse(report_path).metrics_dict()
