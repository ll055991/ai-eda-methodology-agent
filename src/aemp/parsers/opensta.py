"""OpenSTAParser: parses OpenSTA report stdout into structured facts.

Format ground truth (OpenSTA 3.1.0, verified against REAL reports
generated by this platform - see tests/fixtures/reports/opensta/):

- ``report_checks`` prints one block per timing path::

      Startpoint: _15_ (rising edge-triggered flip-flop clocked by clk)
      Endpoint: _17_ (rising edge-triggered flip-flop clocked by clk)
      Path Group: clk
      Path Type: max
      ... delay table ...
                 0.29   slack (MET)

- ``report_worst_slack`` prints ``worst slack max 0.29`` (and ``min``
  for hold analysis when requested);
- ``report_tns`` prints ``tns max 0.00``;
- with ``-no_splash`` there is NO version banner, so ``tool_version``
  is honestly ``None`` (never guessed).

Parsing rules:
- numbers accept ``0.29`` / ``+0.29`` / ``0.290`` / ``-0.01``;
- a report missing ONE metric (e.g. no worst-slack line) is still
  parsed: the metric is absent and a diagnostic records the gap -
  a missing metric is NEVER mapped to 0 (unknown != 0);
- empty or unrecognizable content raises :class:`ReportParseError`.

Units: OpenSTA reports times in the Liberty/SDC time unit; every library
in the demo chain uses ``time_unit : "1ns"``, so slack metrics are
labelled ``_ns``.
"""

from __future__ import annotations

import re

from aemp.parsers.base import ReportParser
from aemp.parsers.errors import ReportParseError
from aemp.parsers.models import (
    Metric,
    ParseDiagnostic,
    ParsedReport,
    TimingPath,
)

__all__ = ["OpenSTAParser"]

_RECOGNIZED_MARKERS = ("Startpoint:", "worst slack", "slack (")

_WORST_SLACK_RE = re.compile(
    r"^\s*worst slack\s+(?P<corner>max|min)\s+"
    r"(?P<value>[-+]?\d+(?:\.\d+)?)\s*$",
    re.MULTILINE,
)
_TNS_RE = re.compile(
    r"^\s*tns\s+(?P<corner>max|min)\s+(?P<value>[-+]?\d+(?:\.\d+)?)\s*$",
    re.MULTILINE,
)
_SLACK_LINE_RE = re.compile(
    r"^\s*(?P<value>[-+]?\d+(?:\.\d+)?)\s+slack\s+"
    r"\((?P<status>MET|VIOLATED|UNCONSTRAINED)\)\s*$"
)
_HEADER_FIELDS = ("Endpoint:", "Path Group:", "Path Type:")


class OpenSTAParser(ReportParser):
    """Parses OpenSTA report stdout (report_checks / worst slack / tns)."""

    tool_name = "opensta"

    def parse_text(self, text: str, *, source: str = "<text>") -> ParsedReport:
        """Parse OpenSTA report *text* into structured facts.

        Raises:
            ReportParseError: If *text* is empty or contains none of the
                known OpenSTA report sections.
        """
        if not text.strip():
            msg = f"Report is empty: {source}"
            raise ReportParseError(msg)
        if not any(marker in text for marker in _RECOGNIZED_MARKERS):
            msg = f"Unrecognized report format (no OpenSTA sections found): {source}"
            raise ReportParseError(msg)

        diagnostics: list[ParseDiagnostic] = []
        metrics: list[Metric] = []

        worst = _WORST_SLACK_RE.search(text)
        if worst is not None and worst.group("corner") == "max":
            metrics.append(
                Metric("sta.wns_ns", float(worst.group("value")), "ns", source)
            )
        else:
            diagnostics.append(
                ParseDiagnostic(
                    severity="warning",
                    code="metric_unavailable",
                    message="no 'worst slack max' line found: sta.wns_ns unavailable",
                )
            )

        tns = _TNS_RE.search(text)
        if tns is not None and tns.group("corner") == "max":
            metrics.append(
                Metric("sta.tns_ns", float(tns.group("value")), "ns", source)
            )
        else:
            diagnostics.append(
                ParseDiagnostic(
                    severity="warning",
                    code="metric_unavailable",
                    message="no 'tns max' line found: sta.tns_ns unavailable",
                )
            )

        paths, path_diagnostics = self._parse_paths(text, source)
        diagnostics.extend(path_diagnostics)
        metrics.append(Metric("sta.path_count", len(paths), "count", source))
        violation_count = sum(1 for p in paths if p.status == "VIOLATED")
        metrics.append(
            Metric("sta.violation_count", violation_count, "count", source)
        )

        return ParsedReport(
            tool=self.tool_name,
            source=source,
            tool_version=None,  # -no_splash reports carry no version banner
            metrics=tuple(metrics),
            paths=tuple(paths),
            diagnostics=tuple(diagnostics),
        )

    def _parse_paths(
        self, text: str, source: str
    ) -> tuple[list[TimingPath], list[ParseDiagnostic]]:
        """Parse report_checks blocks: header fields plus the slack line.

        The full delay table (per-cell arcs) is deliberately NOT parsed in
        M4 - the v1 focus is path summaries and report-level metrics.
        """
        paths: list[TimingPath] = []
        diagnostics: list[ParseDiagnostic] = []
        current: dict[str, str | float | None] | None = None

        for line in text.splitlines():
            if line.startswith("Startpoint:"):
                if current is not None:
                    paths.append(self._build_path(current, source, diagnostics))
                current = {"startpoint": line.removeprefix("Startpoint:").strip()}
                continue
            if current is None:
                continue
            for field in _HEADER_FIELDS:
                if line.startswith(field):
                    current[field.removesuffix(":")] = line.removeprefix(field).strip()
            slack_match = _SLACK_LINE_RE.match(line)
            if slack_match is not None:
                current["slack_ns"] = float(slack_match.group("value"))
                current["status"] = slack_match.group("status")
        if current is not None:
            paths.append(self._build_path(current, source, diagnostics))
        return paths, diagnostics

    @staticmethod
    def _build_path(
        fields: dict[str, str | float | None], source: str, diagnostics: list[ParseDiagnostic]
    ) -> TimingPath:
        slack = fields.get("slack_ns")
        if slack is None:
            diagnostics.append(
                ParseDiagnostic(
                    severity="warning",
                    code="path_slack_unparsed",
                    message=(
                        f"path starting at {fields.get('startpoint', '?')!r} "
                        f"has no parseable slack line"
                    ),
                )
            )
        return TimingPath(
            startpoint=str(fields.get("startpoint", "")),
            endpoint=str(fields.get("Endpoint", "")),
            path_group=str(fields.get("Path Group", "")),
            path_type=str(fields.get("Path Type", "")),
            slack_ns=slack if slack is None else float(slack),  # type: ignore[arg-type]
            status=fields.get("status"),  # type: ignore[arg-type]
        )
